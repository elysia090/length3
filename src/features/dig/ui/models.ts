/**
 * 人物の立体。箱を積んで作る（一覧の舞台・Robot Tune と同じ 1 ビットの網点で
 * 描く）。座標は床の上、一辺 1 が人の肩幅くらい。
 *
 * 箱は [x, y, z, 幅, 高さ, 奥行き]（x, z は底の中心、y は底の高さ）。hot は
 * 琥珀で灯る部分（灯り・カップ・目）。tilt は z 軸まわりの傾き。
 */

export interface Box {
  at: readonly [number, number, number];
  size: readonly [number, number, number];
  hot?: number;
  tilt?: number;
  /** 人物の体の一部（揺れと前のめりに付いてくる）。 */
  body?: boolean;
}

const b = (
  x: number,
  y: number,
  z: number,
  w: number,
  h: number,
  d: number,
  o: Partial<Box> = {},
): Box => ({ at: [x, y, z], size: [w, h, d], body: true, ...o });

const fixed = (
  x: number,
  y: number,
  z: number,
  w: number,
  h: number,
  d: number,
  o: Partial<Box> = {},
) => b(x, y, z, w, h, d, { body: false, ...o });

/** 立っている人。帽子・外套・持ち物を差し替える。 */
function person(o: { hat?: Box[]; coat?: number; prop?: Box[]; head?: number } = {}): Box[] {
  const coat = o.coat ?? 0.62;
  const h = o.head ?? 0.34;
  return [
    b(-0.14, 0, 0, 0.2, 0.62, 0.22),
    b(0.14, 0, 0, 0.2, 0.62, 0.22),
    b(0, 0.6, 0, 0.62, coat + 0.18, 0.36),
    b(-0.38, 0.72, 0, 0.14, 0.6, 0.16),
    b(0.38, 0.72, 0, 0.14, 0.6, 0.16),
    b(0, 1.38 + (coat - 0.62), 0, h, h + 0.04, h),
    ...(o.hat ?? []),
    ...(o.prop ?? []),
  ];
}

function swarm(n: number): Box[] {
  const out: Box[] = [];
  for (let i = 0; i < n; i++) {
    const a = i * 2.399;
    const r = 0.25 + (0.5 * ((i * 37) % 11)) / 11;
    out.push(b(Math.cos(a) * r, 0.05 + ((i * 13) % 7) * 0.12, Math.sin(a) * r, 0.12, 0.06, 0.2));
  }
  return out;
}

