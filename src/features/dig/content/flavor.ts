/**
 * 小さな文。選択も数字も持たない、建物の手ざわり。
 *
 * 放置     地図の上で手を止めていると、ときどき一つ流れる（IDLE）
 * 到着     フロアに着いたときの一文の、別の言い方（ARRIVE）
 * 出来事   下りた先でときどき起きる、選択のない小さな出来事（AUTO）。
 *          三分の一ほどは、硬貨や体や心がほんの少し動く。理由は文の中に書く
 * 身ぶり   向き合っている相手の、次の手の気配（POSTURE）。数は出さない
 * 具合     あなたの体と心の、言葉にした目盛り（VITALS）
 * 時刻     22 時から昼までの、建物の空気（HOURS）
 */

